-- 0304: a member proves they read the address their account was made with.
--
-- Readiness finding R104, the account pre-hijack. Email sign-up stored any
-- address it was handed and never asked whether the person typing it reads
-- that mailbox. A later Google sign-in whose verified address matched was
-- linked to the row and left its password and every session standing, and
-- FOUNDER_EMAILS could then make that row the founder. So anybody could plant
-- a password account at the address a future member would bring to Google.
--
-- `email_verified_at` is when the owner of `users.email` proved they read it:
-- a redeemed address-proof link (together with the account's own session or
-- password), a redeemed set-password link, or a Google sign-in whose verified
-- address is this one (server/lib/emailVerification.ts). While it is NULL, a
-- password on the row is never trusted as the mailbox owner's.
--
-- ONE NULLABLE COLUMN, so this file is expand-only: the previous release
-- names it in no INSERT and no UPDATE (server/repos/users.ts writes the
-- columns it lists), so a rollback leaves it as it stands and new rows get
-- NULL, which reads as unproved, the safe side.
--
-- NO BACKFILL, deliberately. No stored fact tells a planted password from an
-- honest one on a row that exists today, so every existing row starts
-- unproved. Nobody is locked out by that: signing in by password never asks
-- for the proof. What it costs an existing member is one thing, once, and only
-- if they hold a password AND sign in with Google: that password ends and
-- their other devices sign out, while they are signed in by Google. Backfilling
-- instead would mark any account planted before this release as its victim's
-- own, for good.
ALTER TABLE `users`
  ADD COLUMN `email_verified_at` timestamp NULL;
