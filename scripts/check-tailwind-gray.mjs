#!/usr/bin/env node
/**
 * The Tailwind-default-gray ratchet: a founder's brand colour should reach
 * every surface a member reads text on. It cannot reach a colour Tailwind
 * bakes in from its own built-in palette.
 *
 * WHY THIS IS A DIFFERENT SHAPE FROM check-theme-literals.mjs. That guard
 * catches a literal hex/rgb/hsl/oklch value written directly into a
 * className or style prop: a LITERAL. `text-gray-500` is not a literal in
 * that sense: it carries no hex code, and check-theme-literals.mjs's own
 * regexes (HEX, FUNC) do not and should not match it. It is Tailwind's own
 * default colour SCALE, generated by the framework regardless of anything
 * this repo's design-token layer (shared/brandTokens.ts, client/src/index.css)
 * emits. A village's seed colour re-themes every `--tone-*` var and every
 * token-backed utility (`text-foreground`, `text-muted-foreground`,
 * `text-teal-deep`, ...); it can never re-theme `text-gray-500`, because
 * that utility's colour is compiled from Tailwind's palette, not from this
 * repo's CSS custom properties, at build time. Two different bypasses of the
 * same design intent, so two different guards, matching two different fix
 * shapes: check-theme-literals.mjs wants a literal routed through a
 * `--tone-*` var; this one wants a semantic token (`text-foreground`,
 * `text-muted-foreground`, or another @theme inline entry) in place of the
 * numbered gray.
 *
 * SCOPE, DELIBERATELY NARROW: `text-gray-*` only, not `bg-gray-*` or
 * `border-gray-*`. Those are common as neutral SURFACE/DIVIDER colours where
 * staying grey (or platform-neutral) is often the actual design intent, not
 * a founder's brand hue; text is where a member reads the village's voice,
 * and where the brief that opened this guard measured 1,287 occurrences.
 * Widening the scope is a real option for later, not folded in here, so
 * this guard's number keeps meaning one specific thing.
 *
 * THE RATCHET, same discipline as scripts/check-theme-literals.mjs and
 * scripts/check-image-budget.mjs: the baseline in
 * scripts/tailwind-gray-baseline.json is a per-file count that may only ever
 * fall, and `--update-baseline` REFUSES to write a total higher than the one
 * already committed. A brand-new file starts at zero, so it is born clean.
 *
 * A genuine false positive (a string that contains the substring
 * `text-gray-NNN` but is not a rendered Tailwind class (an error message
 * quoting a class name, a comment) gets an inline `gray-ok: <reason>` marker,
 * same spelling convention as check-theme-literals.mjs's `theme-ok:` and
 * check-brand-refs.mjs's `brand-ok:`.
 *
 * Usage:
 *   node scripts/check-tailwind-gray.mjs                    # the gate
 *   node scripts/check-tailwind-gray.mjs --json              # machine readable
 *   node scripts/check-tailwind-gray.mjs --update-baseline   # only ever downward
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { stripComments } from "./brand-strip.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SCAN_ROOT = path.join(ROOT, "client", "src");
const BASELINE_PATH = path.join(ROOT, "scripts", "tailwind-gray-baseline.json");

const rel = (p) => path.relative(ROOT, p).split(path.sep).join("/");

function walk(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(full, out);
    } else if (entry.name.endsWith(".tsx")) {
      out.push(full);
    }
  }
  return out;
}

/** `text-gray-NNN`, any Tailwind variant prefix (hover:, dark:, md:, ...)
 *  ahead of it matches too since the pattern is unanchored and a colon is
 *  not a word character. `\b` on both ends so `text-gray-500` inside a
 *  longer identifier (there are none in this codebase, but a guard should
 *  not assume) is not partially matched. */
const GRAY = /\btext-gray-\d+\b/g;

function countHits(line) {
  return line.match(GRAY) ?? [];
}

/**
 * Whether a line is still inside a block comment by the time it ends, given
 * whether it started inside one. Two things a plain same-line regex test
 * gets wrong, both caught live in this tree while building this guard:
 *
 * 1. A slash-star opener can sit INSIDE A STRING LITERAL and mean nothing -
 *    accept="image" followed by a slash and a star for the MIME wildcard is
 *    an ordinary, common file-input attribute, not a comment. A same-line
 *    test that does not know about string context reads it as an UNCLOSED
 *    block comment (no closer later on that line), then marks every line
 *    after it "inside a comment" until some later line happens to contain a
 *    closer by coincidence - silently dropping real code below it. Caught in
 *    IdentityPackPanel.tsx (2 text-gray occurrences went uncounted before
 *    this fix); ModuleDetail.tsx and WorkWithUs.tsx carry the same
 *    attribute pattern. So this function tracks string state and ignores a
 *    slash-star found inside a string.
 *
 * 2. The FIRST fix for (1), tracking string state naively across the WHOLE
 *    line, broke worse: this codebase's comments are prose-heavy and full of
 *    ordinary apostrophes ("the API's users", "founder's colour", "isn't"),
 *    and a quote tracker that treats every apostrophe as a string opener
 *    starts "quoting" from the first one and never lets go, so a real
 *    closer later on that SAME comment line - a one-line JSDoc comment whose
 *    text happens to contain an apostrophe before the closing marker - was
 *    swallowed as "inside a string" and never recognised as a closer.
 *    Measured: this single bug undercounted
 *    the tree by dozens of occurrences (EventsAdminPanel.tsx alone lost 28)
 *    before being caught and fixed. The fix: once a REAL slash-star opener
 *    is found (outside a string), stop honouring quote characters entirely
 *    until the matching closer - comment text is prose, not code, and no
 *    apostrophe inside it should ever start a string.
 *
 * check-theme-literals.mjs's own opener/closer regexes have neither of these
 * two protections and carry the same risk; not fixed there, since that file
 * is not this lane's to edit - flagged in this lane's report instead.
 */
function commentStateAfterLine(line, startsInComment) {
  let quote = null;
  let inComment = startsInComment;
  for (let i = 0; i < line.length; i += 1) {
    const c = line[i];
    if (inComment) {
      if (c === "*" && line[i + 1] === "/") { inComment = false; i += 1; }
      continue;
    }
    if (quote) {
      if (c === "\\") { i += 1; continue; }
      if (c === quote) quote = null;
      continue;
    }
    if (c === '"' || c === "'" || c === "`") { quote = c; continue; }
    if (c === "/" && line[i + 1] === "*") { inComment = true; i += 1; continue; }
  }
  return inComment;
}

/**
 * `gray-ok:` waives a line the same way check-theme-literals.mjs's
 * `theme-ok:` does, including the one-line-ahead arming for a comment that
 * cannot share its line with the code it excuses.
 */
function scanFile(file) {
  const ext = path.extname(file);
  const lines = fs.readFileSync(file, "utf8").split("\n");
  let count = 0;
  let waived = 0;
  const hits = [];
  let inBlock = false;
  let pendingWaiver = false;
  lines.forEach((line, i) => {
    const wasInBlock = inBlock;
    inBlock = commentStateAfterLine(line, wasInBlock);
    const hasMarker = /gray-ok:/.test(line);
    const code = wasInBlock ? "" : stripComments(line, ext);
    const found = countHits(code);
    const isBlankOrCommentOnly = code.trim() === "";

    if (hasMarker) {
      if (found.length > 0) { waived += 1; pendingWaiver = false; return; }
      pendingWaiver = true;
      return;
    }
    if (isBlankOrCommentOnly) return;
    if (found.length > 0 && pendingWaiver) {
      waived += 1;
      pendingWaiver = false;
      return;
    }
    pendingWaiver = false;
    if (found.length > 0) {
      count += found.length;
      hits.push({ line: i + 1, text: line.trim().slice(0, 140) });
    }
  });
  return { count, waived, hits };
}

/**
 * THE LIGHT-SURFACE ZONE, and why a numbered gray is the RIGHT answer inside it.
 *
 * Rye's ruling, 2026-09-04: the admin panel is a light-only workspace, on
 * purpose. That is a product decision and not an oversight, and it changes
 * what this guard should ask of the files below.
 *
 * Outside this zone a numbered gray is debt, because a member's page follows
 * the theme the village chose and `text-gray-500` cannot. INSIDE it, a
 * semantic token is the DEFECT: these surfaces paint a hardcoded `bg-white`
 * (93 of them at the time of writing), so `text-foreground` on one of them
 * renders near-white text on white the moment a founder switches to dark. The
 * repo has already paid for that shape once, on Profile.tsx, where a
 * responsive token on a frozen surface measured 2.76 to 1.
 *
 * So the zone is not an amnesty. It is this guard declining to push a file
 * toward a bug. A file here must pair its colours consistently: fixed text on
 * a fixed surface. Move any of this code onto a themed surface and it leaves
 * the zone by path and is counted again, which is exactly what should happen.
 *
 * DELIBERATELY NARROW. Two entries, both unambiguously the founder's
 * workspace. Profile.tsx is NOT here: it has the same frozen-surface problem
 * and no ruling, so it stays counted and stays visible.
 */
const LIGHT_SURFACES = [
  "client/src/pages/Admin.tsx",
  "client/src/components/admin/",
];

const inLightSurfaceZone = (relPath) =>
  LIGHT_SURFACES.some((p) => relPath === p || relPath.startsWith(p));

const files = walk(SCAN_ROOT).sort();
const counts = {};
const details = {};
let totalWaivers = 0;
let zoneSkipped = 0;
for (const file of files) {
  const r = rel(file);
  // The founder's workspace is fixed-light by ruling; see LIGHT_SURFACES.
  if (inLightSurfaceZone(r)) { zoneSkipped += 1; continue; }
  const { count, waived, hits } = scanFile(file);
  totalWaivers += waived;
  if (count > 0) { counts[r] = count; details[r] = hits; }
}
const total = Object.values(counts).reduce((n, v) => n + v, 0);

if (process.argv.includes("--update-baseline")) {
  const baseline = fs.existsSync(BASELINE_PATH) ? JSON.parse(fs.readFileSync(BASELINE_PATH, "utf8")) : null;
  const baselineTotal = baseline ? Object.values(baseline.files ?? baseline).reduce((n, v) => n + v, 0) : Infinity;
  if (total > baselineTotal) {
    console.error(
      `::error::refusing to raise the tailwind-gray baseline: ${total} is above the recorded ${baselineTotal}. ` +
      `This number only ever falls. Route the new text colour through a semantic token (text-foreground, ` +
      `text-muted-foreground, or another @theme inline entry in client/src/index.css) instead of Tailwind's ` +
      `default gray scale.`);
    process.exit(1);
  }
  fs.writeFileSync(
    BASELINE_PATH,
    `${JSON.stringify({ totalLiterals: total, files: counts }, null, 2)}\n`,
  );
  console.log(`tailwind-gray baseline lowered to ${total} across ${Object.keys(counts).length} file(s).`);
  process.exit(0);
}

if (process.argv.includes("--json")) {
  console.log(JSON.stringify({ total, files: counts, waivers: totalWaivers }));
}

const baseline = fs.existsSync(BASELINE_PATH) ? JSON.parse(fs.readFileSync(BASELINE_PATH, "utf8")) : { totalLiterals: 0, files: {} };
const baselineFiles = baseline.files ?? {};
const baselineTotal = baseline.totalLiterals ?? Object.values(baselineFiles).reduce((n, v) => n + v, 0);

const failures = [];
for (const [file, count] of Object.entries(counts)) {
  const allowed = baselineFiles[file] ?? 0;
  if (count > allowed) {
    failures.push({
      file,
      reason: `${count} text-gray-* Tailwind-default-palette class(es), baseline allows ${allowed}, the ratchet only turns down`,
      hits: details[file].slice(0, 5),
    });
  }
}

if (failures.length) {
  console.error("\nTAILWIND-GRAY GUARD FAILED: a founder's colour cannot reach Tailwind's own default palette.\n");
  console.error("Route the colour through a semantic token instead: text-foreground / text-muted-foreground, or");
  console.error("another @theme inline entry in client/src/index.css (teal-deep, amber-ink, sage, ...).\n");
  for (const f of failures) {
    console.error(`  ${f.file}: ${f.reason}`);
    for (const h of f.hits) console.error(`      ${f.file}:${h.line}: ${h.text}`);
  }
  console.error(`\nIf a hit is a genuine false positive (not a rendered class), add \`gray-ok: <reason>\` on that line.`);
  console.error(`If you REMOVED occurrences, lower the baseline: node scripts/check-tailwind-gray.mjs --update-baseline\n`);
  process.exit(1);
}

console.log(
  `Tailwind-gray guard passed. ${total} text-gray-* class(es) across ${Object.keys(counts).length} file(s) ` +
  // The zone is PRINTED on every run. An exemption nobody sees is an
  // exemption that outlives its reason.
  `(${zoneSkipped} file(s) skipped as fixed-light admin surfaces) ` +
  `(baseline ${baselineTotal}); ${totalWaivers} waiver(s) in force.`,
);
