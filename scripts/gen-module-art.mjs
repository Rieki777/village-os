#!/usr/bin/env node
/**
 * Writes `client/src/components/modules/bundledModuleArt.ts` from the art
 * manifest, `client/public/images/modules/manifest.json`.
 *
 * `ModuleArt` needs one fact at build time: which modules ship a bundled file.
 * The manifest records it, but importing a file from `client/public` makes the
 * vite dev server warn "Assets in public directory cannot be imported from
 * JavaScript" on every load, and inlines each entry's generation metadata the
 * card never reads. So the file names are copied out, by this script only.
 *
 * The copy cannot drift silently: `client/src/lib/moduleImages.test.ts` fails
 * when it disagrees with the manifest or with the files on disk, and its
 * message names this script.
 *
 * Usage: node scripts/gen-module-art.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const MANIFEST = path.join(ROOT, "client", "public", "images", "modules", "manifest.json");
const OUT = path.join(ROOT, "client", "src", "components", "modules", "bundledModuleArt.ts");

const { assets } = JSON.parse(fs.readFileSync(MANIFEST, "utf8"));
const lines = Object.keys(assets)
  .sort()
  .map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(String(assets[id].file))},`);

fs.writeFileSync(OUT, `/**
 * GENERATED by \`node scripts/gen-module-art.mjs\` from
 * client/public/images/modules/manifest.json. Do not edit by hand; rerun it.
 * \`client/src/lib/moduleImages.test.ts\` fails while this disagrees with the
 * manifest or with the files on disk.
 */
export const BUNDLED_MODULE_ART: Readonly<Record<string, string>> = {
${lines.join("\n")}
};
`);
console.log(`wrote ${path.relative(ROOT, OUT)}: ${lines.length} module(s) with bundled art`);
